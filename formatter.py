"""Format book deals as Telegram-friendly Markdown."""

from datetime import datetime, timezone
from typing import Any


def _format_book_entry(book: dict[str, Any]) -> str:
    """Format a single book as a report line."""
    price_str = f"${book['price']:.2f}" if book.get("price") is not None else "N/A"
    title = book.get("title", "Unknown Title")
    author = book.get("author", "")
    url = book.get("url", "")
    
    savings = ""
    list_price = book.get("list_price")
    savings_pct = book.get("savings_pct")
    if list_price and savings_pct:
        savings = f" ~~was ${list_price:.2f}~~ \\({savings_pct}% off\\)"
    elif list_price:
        savings = f" ~~was ${list_price:.2f}~~"
    elif savings_pct:
        savings = f" \\({savings_pct}% off\\)"
    
    if len(title) > 80:
        title = title[:77] + "..."
    
    line = f"\\- *{title}*"
    if author:
        line += f" — _{author}_"
    line += f" — {price_str}"
    if savings:
        line += f" {savings}"
    if url:
        line += f" — [Link]({url})"
    return line


def format_report(books: list[dict[str, Any]], new_count: int, 
                  dropped_count: int) -> str:
    """Format the daily deals report with tracked authors section first."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    
    lines = [
        f"📚 *Kindle SFF Deals — {now}*",
        "",
    ]
    
    if not books:
        lines.append("No Fantasy or Sci\\-Fi deals found today\\.")
        lines.append("")
        lines.append(f"_📊 Stats: {new_count} new, {dropped_count} price drops today_")
        return "\n".join(lines)
    
    # Split into tracked authors vs others
    tracked = [b for b in books if b.get("tracked_author")]
    others = [b for b in books if not b.get("tracked_author")]
    
    lines.append(f"_{len(books)} deals found_ | 🆕 {new_count} new | 📉 {dropped_count} price drops")
    lines.append("")
    
    # Tracked authors section
    if tracked:
        lines.append("*⭐ Your Authors*")
        lines.append("")
        for book in tracked:
            lines.append(_format_book_entry(book))
        lines.append("")
    
    # All other deals section
    if others:
        lines.append("*📖 All Deals*")
        lines.append("")
        for book in others:
            lines.append(_format_book_entry(book))
        lines.append("")
    
    lines.append("_🤖 Generated by Kindle Deals Bot_")
    
    # Cover images as MEDIA tags
    media_lines = []
    for book in books:
        cover_path = book.get("cover_path")
        if cover_path:
            media_lines.append(f"MEDIA:{cover_path}")
    
    if media_lines:
        lines.append("")
        lines.extend(media_lines)
    
    return "\n".join(lines)


def format_empty_report() -> str:
    """Report when no sources returned data at all."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return (
        f"📚 *Kindle SFF Deals — {now}*\n\n"
        "⚠️ Could not fetch deals from any source today\\. "
        "Amazon may be blocking requests or the selectors need updating\\.\n\n"
        "_🤖 Generated by Kindle Deals Bot_"
    )
